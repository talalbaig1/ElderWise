function buildCheckIns(): CheckInResponse[] {
  const items: CheckInResponse[] = [];
  const statuses: CheckInResponse["status"][] = [
    "taken",
    "taken",
    "taken",
    "delayed",
    "missed",
    "pending",
  ];

  for (let day = 0; day < 28; day++) {
    statuses.forEach((status, idx) => {
      const lovedOne = mockLovedOnes[idx % mockLovedOnes.length];
      items.push({
        id: `ci-${day}-${idx}`,
        lovedOneId: lovedOne.id,
        routineId: mockMedications[idx % mockMedications.length].id,
        routineKind: idx % 3 === 0 ? "medication" : idx % 3 === 1 ? "food" : "health",
        scheduledAt: iso(day, 8 + (idx % 8), 0),
        respondedAt:
          status === "upcoming" || status === "pending"
            ? undefined
            : iso(day, 8 + (idx % 8), 12),
        status,
        response:
          status === "taken" ? "yes" : status === "missed" ? "no" : "remind_later",
        channel: "simulated",
      });
    });
  }

  return items;
}

